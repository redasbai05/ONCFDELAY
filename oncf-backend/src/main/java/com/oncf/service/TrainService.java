package com.oncf.service;

import com.oncf.model.Notification;
import com.oncf.model.Train;
import com.oncf.model.Voyage;
import com.oncf.model.Voyageur;
import com.oncf.repository.*;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.ArrayList;
import java.util.List;

@Service
@RequiredArgsConstructor
public class TrainService {

    private final TrainRepository trainRepository;
    private final VoyageRepository voyageRepository;
    private final ReservationRepository reservationRepository;
    private final NotificationRepository notificationRepository;

    public List<Train> getAllTrains() {
        return trainRepository.findAll();
    }

    public Train getTrainById(Long id) {
        return trainRepository.findById(id)
                .orElseThrow(() -> new RuntimeException("Train not found with id: " + id));
    }

    public Train createTrain(Train train) {
        if (train.getEtat() == null) {
            train.setEtat("A_L_HEURE");
        }
        return trainRepository.save(train);
    }

    public void deleteTrain(Long id) {
        trainRepository.deleteById(id);
    }

    @Transactional
    public void declareDelay(Long trainId, int minutes, String raison) {
        Train train = getTrainById(trainId);
        train.setEtat("EN_RETARD");
        trainRepository.save(train);

        List<Voyage> voyages = voyageRepository.findByTrainId(trainId);
        for (Voyage voyage : voyages) {
            voyage.setMinutesRetard(voyage.getMinutesRetard() + minutes);
            voyageRepository.save(voyage);

            // Backfill: subscribe existing reservation holders as observers
            reservationRepository.findByVoyageId(voyage.getId())
                    .stream()
                    .map(r -> r.getVoyageur())
                    .forEach(train::addObserver);
        }

        // Observer pattern: notify all subscribed voyageurs
        String message = String.format(
                "Retard: Train %s, retard de %d min. Raison: %s",
                train.getNumeroTrain(), minutes, raison
        );
        train.notifyObservers(message);

        // Persist all pending notifications generated by observers
        List<Notification> allNotifications = new ArrayList<>();
        for (Voyageur v : train.getObservers()) {
            allNotifications.addAll(v.drainPendingNotifications());
        }
        notificationRepository.saveAll(allNotifications);
    }
}
